import { mount, flushPromises } from '@vue/test-utils'
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import CheckinView from '../CheckinView.vue'

const { getCheckin, claimCheckin, refreshUser, fetchPublicSettings, verifyAction, resetCaptcha } = vi.hoisted(() => ({ getCheckin: vi.fn(), claimCheckin: vi.fn(), refreshUser: vi.fn(), fetchPublicSettings: vi.fn(), verifyAction: vi.fn(), resetCaptcha: vi.fn() }))
vi.mock('@/api/checkin', () => ({ getCheckin, claimCheckin }))
vi.mock('@/stores/auth', () => ({ useAuthStore: () => ({ user: { balance: 12 }, refreshUser }) }))
vi.mock('@/stores/app', () => ({ useAppStore: () => ({ fetchPublicSettings }) }))
vi.mock('@/components/CaptchaChallenge.vue', () => ({ default: { template: '<div class="captcha-test" />', setup: (_: unknown, { expose }: { expose: (value: unknown) => void }) => { expose({ verifyAction, reset: resetCaptcha }) } } }))
vi.mock('vue-i18n', () => ({ useI18n: () => ({ t: (key: string) => key }) }))
vi.mock('@/components/layout/AppLayout.vue', () => ({ default: { template: '<div><slot /></div>' } }))
const sample = (checked = false) => ({ date: '2026-09-18', next_reset_at: '2026-09-19T00:00:00+08:00', checked_in: checked, reward_cents: checked ? 10 : 0, history: checked ? [{ date: '2026-09-18', reward_cents: 10, created_at: '2026-09-18T01:00:00Z' }] : [], snapshot: { version: 1, active_days: 0, streak_days: 1, spend: 0, has_recharge: false, activity_score: 0, streak_score: 40 / 7, spend_score: 0, recharge_score: 0, score: 40 / 7, prizes: [1, 3, 10, 50, 100].map(cents => ({ cents, probability: 20 })) } })

describe('daily check-in', () => {
  beforeEach(() => {
    vi.useFakeTimers(); vi.clearAllMocks()
    vi.stubGlobal('matchMedia', vi.fn(() => ({ matches: false })))
    getCheckin.mockResolvedValue(sample()); claimCheckin.mockResolvedValue(sample(true)); refreshUser.mockResolvedValue(undefined)
    fetchPublicSettings.mockResolvedValue({ tencent_captcha_enabled: true, tencent_captcha_app_id: '123456789' })
    verifyAction.mockResolvedValue({ token: 'verified-ticket', randstr: 'verified-randstr' })
  })
  afterEach(() => { vi.useRealTimers(); vi.unstubAllGlobals() })
  it('locks duplicate clicks, animates to server award and refreshes balance', async () => {
    const wrapper = mount(CheckinView); await flushPromises()
    const button = wrapper.get('.claim-button')
    await button.trigger('click'); await button.trigger('click'); await flushPromises()
    expect(claimCheckin).toHaveBeenCalledTimes(1)
    expect(claimCheckin).toHaveBeenCalledWith({ tencent_captcha_ticket: 'verified-ticket', tencent_captcha_randstr: 'verified-randstr' })
    expect(button.attributes('disabled')).toBeDefined()
    expect(wrapper.get('.disc').attributes('style')).toContain('1656deg')
    await vi.advanceTimersByTimeAsync(3300); await flushPromises()
    expect(wrapper.find('.reward-result').exists()).toBe(true)
    expect(refreshUser).toHaveBeenCalledTimes(1)
    expect(button.text()).toBe('checkin.tomorrow'); wrapper.unmount()
  })
  it('restores an already committed award on reload without another claim', async () => {
    getCheckin.mockResolvedValue(sample(true))
    const wrapper = mount(CheckinView); await flushPromises()
    expect(wrapper.get('.claim-button').attributes('disabled')).toBeDefined()
    expect(wrapper.get('.disc').attributes('style')).toContain('216deg')
    expect(claimCheckin).not.toHaveBeenCalled(); wrapper.unmount()
  })
  it('keeps a failed request retryable and preserves a committed result when balance refresh fails', async () => {
    claimCheckin.mockRejectedValueOnce(new Error('timeout'))
    refreshUser.mockRejectedValue(new Error('offline'))
    const wrapper = mount(CheckinView); await flushPromises()
    await wrapper.get('.claim-button').trigger('click'); await flushPromises()
    expect(wrapper.get('[role="alert"]').text()).toContain('checkin.claimError')
    expect(wrapper.get('.claim-button').attributes('disabled')).toBeUndefined()
    await wrapper.get('.claim-button').trigger('click'); await flushPromises()
    await vi.advanceTimersByTimeAsync(3300); await flushPromises()
    expect(wrapper.find('[role="alert"]').exists()).toBe(false)
    expect(wrapper.find('.reward-result').exists()).toBe(true); wrapper.unmount()
  })
  it('reloads after Beijing midnight and cleans up its timer', async () => {
    vi.setSystemTime(new Date('2026-09-18T15:59:50Z'))
    getCheckin.mockResolvedValueOnce(sample(true)).mockResolvedValue({ ...sample(), date: '2026-09-19', next_reset_at: '2026-09-20T00:00:00+08:00' })
    const wrapper = mount(CheckinView); await flushPromises()
    await vi.advanceTimersByTimeAsync(30000); await flushPromises()
    expect(getCheckin).toHaveBeenCalledTimes(2)
    expect(wrapper.get('.claim-button').attributes('disabled')).toBeUndefined()
    wrapper.unmount(); expect(vi.getTimerCount()).toBe(0)
  })
  it('does not submit when verification is cancelled', async () => {
    verifyAction.mockResolvedValue(null)
    const wrapper = mount(CheckinView); await flushPromises()
    await wrapper.get('.claim-button').trigger('click'); await flushPromises()
    expect(claimCheckin).not.toHaveBeenCalled()
    expect(resetCaptcha).toHaveBeenCalled()
    expect(wrapper.get('.claim-button').attributes('disabled')).toBeUndefined()
    wrapper.unmount()
  })
  it.each([null, {}, { turnstile_enabled: true, turnstile_site_key: 'site' }, { tencent_captcha_enabled: true, tencent_captcha_app_id: 'id', aliyun_captcha_enabled: true }])('blocks claims until configuration and proof are ready: %j', async settings => {
    fetchPublicSettings.mockResolvedValue(settings)
    const wrapper = mount(CheckinView); await flushPromises()
    expect(wrapper.get('.claim-button').attributes('disabled')).toBeDefined()
    await wrapper.get('.claim-button').trigger('click')
    expect(claimCheckin).not.toHaveBeenCalled(); wrapper.unmount()
  })
})
